    /// Erase the simple annotation forms the emitter produces (test-only;
    /// lets node run the output without a TS toolchain). Dependency-free:
    /// scans for `: <SimpleTy>` followed by one of `, ) { = ; <space>`.
    pub(super) fn strip_ts(code: &str) -> String {
        const TYS: [&str; 16] = [
            "Record<string, any>",
            "Promise<Record<string, any>>",
            "Promise<any[]>",
            "Promise<string>",
            "Promise<number>",
            "Promise<boolean>",
            "Promise<null>",
            "Promise<any>",
            "Promise<void>",
            "string",
            "number",
            "boolean",
            "null",
            "any[]",
            "any",
            "void",
        ];
        let mut out = String::with_capacity(code.len());
        let mut rest = code;
        while let Some(pos) = rest.find(": ") {
            let after = &rest[pos + 2..];
            let hit = TYS.iter().find_map(|t| {
                after
                    .strip_prefix(t)
                    .filter(|a2| a2.starts_with([',', ')', '{', '=', ';', ' ']))
                    .map(|_| t)
            });
            match hit {
                Some(t) => {
                    out.push_str(&rest[..pos]);
                    rest = &after[t.len()..];
                }
                None => {
                    out.push_str(&rest[..pos + 2]);
                    rest = after;
                }
            }
        }
        out.push_str(rest);
        out
    }

