//! Nudge TypeScript codegen (design §14, v0.3c) — second backend.
//!
//! Emits a single `.ts` file importing `./nudge_runtime.ts`. MVP subset:
//! type aliases, tools, fns (let/return/assert), llm calls, merge, and the
//! expression forms; annotations are limited to simple TS names so tests
//! can erase them with a regex (see `strip_ts` in the tests). Deferred to
//! the full backend: `agent` blocks, `stream let` streaming, par
//! scheduling, and replay-driver tests — emitted as warning comments.

use crate::ast::*;
use std::cell::RefCell;
use std::collections::{HashMap, HashSet};

// The set of functions that (transitively) reach an `llm` call and must therefore
// be `async` (real providers are async HTTP). Consulted by `ts()` to emit `await`
// at calls and by the function emitter to emit `async function`. Kept in a
// thread-local so the recursive `ts()`/`emit_body()` don't need a new parameter.
thread_local! {
    static ASYNC_FNS: RefCell<HashSet<String>> = RefCell::new(HashSet::new());
}
fn is_async_fn(name: &str) -> bool {
    ASYNC_FNS.with(|s| s.borrow().contains(name))
}

/// Does the emitted text call `name(` (a top-level call, not a method/property)?
fn calls_fn(emitted: &str, name: &str) -> bool {
    let pat = format!("{name}(");
    let bytes = emitted.as_bytes();
    let mut idx = 0;
    while let Some(rel) = emitted[idx..].find(&pat) {
        let abs = idx + rel;
        let prev_ok = abs == 0 || {
            let b = bytes[abs - 1];
            !(b.is_ascii_alphanumeric() || b == b'_' || b == b'.')
        };
        if prev_ok {
            return true;
        }
        idx = abs + 1;
    }
    false
}

fn collect_bodies(items: &[Item], out: &mut Vec<(String, Vec<Stmt>)>) {
    for item in items {
        match item {
            Item::Fn { name, body, .. } | Item::View { name, body, .. } => {
                out.push((name.clone(), body.clone()));
            }
            Item::Agent { fns, .. } => collect_bodies(fns, out),
            _ => {}
        }
    }
}

/// Least fixed point: a function is async if its body contains an llm call OR it
/// calls an already-async user function. UI helpers/tools stay synchronous.
fn compute_async_fns(
    items: &[Item],
    aliases: &HashSet<String>,
    sigs: &HashMap<String, Vec<String>>,
) -> HashSet<String> {
    let mut bodies = Vec::new();
    collect_bodies(items, &mut bodies);
    // Reset the thread-local so this detection pass emits calls WITHOUT await.
    ASYNC_FNS.with(|s| *s.borrow_mut() = HashSet::new());
    // Emit each body once (ASYNC_FNS empty, so calls are not awaited yet) and
    // inspect the text — reuses the emitter instead of an AST walker.
    let emitted: Vec<(String, String)> = bodies
        .iter()
        .map(|(n, b)| (n.clone(), emit_body(b, aliases, sigs, None, &mut 0)))
        .collect();
    let mut async_fns: HashSet<String> = HashSet::new();
    for (n, e) in &emitted {
        if e.contains("rt.llmCall(") || e.contains("rt.llmStream(") {
            async_fns.insert(n.clone());
        }
    }
    loop {
        let mut changed = false;
        for (n, e) in &emitted {
            if async_fns.contains(n) {
                continue;
            }
            for a in &async_fns {
                if calls_fn(e, a) {
                    async_fns.insert(n.clone());
                    changed = true;
                    break;
                }
            }
        }
        if !changed {
            break;
        }
    }
    async_fns
}

pub fn emit_ts(items: &[Item]) -> String {
    let aliases: HashSet<String> = items
        .iter()
        .filter_map(|i| match i {
            Item::TypeAlias { name, .. } => Some(name.clone()),
            _ => None,
        })
        .collect();

    let mut out = String::new();
    out.push_str(&format!(
        "// Generated by nudgec {} — do not edit.\nimport * as rt from \"./nudge_runtime.ts\";\n",
        env!("CARGO_PKG_VERSION")
    ));
    // B6: version compatibility — old runtimes without the hook skip it
    out.push_str(&format!(
        "rt.compatibilityCheck?.(\"{}\");\n",
        env!("CARGO_PKG_VERSION")
    ));
    if crate::codegen::has_ui_items(items) {
        out.push_str("\n\n");
        out.push_str(UI_RUNTIME_TS);
    }
    let mut has_main = false;
    // callee parameter order — JS has no named arguments, so kwargs are
    // reordered into positional slots at the call site
    let sigs: HashMap<String, Vec<String>> = items
        .iter()
        .flat_map(|i| match i {
            Item::Fn { name, params, .. }
            | Item::Tool { name, params, .. }
            | Item::View { name, params, .. } => {
                vec![(
                    name.clone(),
                    params.iter().map(|p| p.name.clone()).collect(),
                )]
            }
            // agent fns live in the same namespace (the checker enforces
            // uniqueness, E0102)
            Item::Agent { fns, .. } => fns
                .iter()
                .filter_map(|f| match f {
                    Item::Fn { name, params, .. } | Item::View { name, params, .. } => Some((
                        name.clone(),
                        params.iter().map(|p| p.name.clone()).collect(),
                    )),
                    _ => None,
                })
                .collect(),
            _ => vec![],
        })
        .collect();
    // Compute which functions must be async (those transitively reaching an llm
    // call), then publish it for ts()/emit_body to consult during emission.
    ASYNC_FNS.with(|s| *s.borrow_mut() = compute_async_fns(items, &aliases, &sigs));
    // test slugs can collide ("a b" vs "a_b") — suffix duplicates
    let mut test_slugs: HashMap<String, usize> = HashMap::new();
    for item in items {
        out.push_str("\n\n");
        match item {
            Item::TypeAlias { name, ty } => {
                out.push_str(&format!(
                    "const {name} = rt.schema({});",
                    schema_ts(ty, &aliases, &sigs)
                ));
            }
            Item::Fn {
                name,
                params,
                ret,
                body,
                ..
            } => {
                let ps = params
                    .iter()
                    .map(|p| format!("{}: {}", p.name, ty_ts(&p.ty, &aliases)))
                    .collect::<Vec<_>>()
                    .join(", ");
                let _kw = if is_async_fn(name) {
                    "async function"
                } else {
                    "function"
                };
                let _ret = {
                    let r = ty_ts(ret, &aliases);
                    if is_async_fn(name) {
                        format!("Promise<{r}>")
                    } else {
                        r
                    }
                };
                out.push_str(&format!("{_kw} {name}({ps}): {_ret} {{\n"));
                out.push_str(&emit_body(body, &aliases, &sigs, None, &mut 0));
                out.push('}');
                if name == "main" {
                    has_main = true;
                }
            }
            Item::Tool {
                name,
                params,
                fields,
                ..
            } => {
                let ps = params
                    .iter()
                    .map(|p| format!("{}: {}", p.name, ty_ts(&p.ty, &aliases)))
                    .collect::<Vec<_>>()
                    .join(", ");
                // named arguments (v1.2.1): MCP tools/call expects an
                // `arguments` object keyed by parameter name — keep the
                // TS stub in parity with the python one
                let arg_list = params
                    .iter()
                    .map(|p| format!("\"{0}\": {0}", p.name))
                    .collect::<Vec<_>>()
                    .join(", ");
                let server = crate::codegen::impl_server(fields)
                    .map(|s| format!(", {{ server: {} }}", js_str(&s)))
                    .unwrap_or_default();
                out.push_str(&format!(
                    "function {name}({ps}): any {{\n  return rt.toolStub(\"{name}\", {{{arg_list}}}{server});\n}}"
                ));
            }
            Item::Test { name, body } => {
                out.push_str(&format!(
                    "function nudge_test_{}(): void {{\n",
                    crate::codegen::unique_slug(&slug_ts(name), &mut test_slugs)
                ));
                let mut prop_id = 0;
                out.push_str(&emit_body(body, &aliases, &sigs, None, &mut prop_id));
                out.push('}');
            }
            Item::Agent { name, state, fns } => {
                // agent state lowering (v1.6): mirrors the python backend —
                // a runtime Proxy checkpoints every state write
                let defaults = state
                    .iter()
                    .map(|(f, _, d)| format!("\"{f}\": {}", ts(d, &aliases, &sigs)))
                    .collect::<Vec<_>>()
                    .join(", ");
                out.push_str(&format!(
                    "const _state_{name} = rt.agentState(\"{name}\", {{{defaults}}});"
                ));
                // list-typed state fields drive the += → .concat lowering
                let list_fields: Vec<String> = state
                    .iter()
                    .filter(|(_, ty, _)| matches!(ty, TypeExpr::List(_)))
                    .map(|(f, _, _)| f.clone())
                    .collect();
                for f in fns {
                    match f {
                        Item::Fn {
                            name: fn_name,
                            params,
                            body,
                            effects,
                            ..
                        } => {
                            let ps = params
                                .iter()
                                .map(|p| format!("{}: {}", p.name, ty_ts(&p.ty, &aliases)))
                                .collect::<Vec<_>>()
                                .join(", ");
                            let fx = if effects.is_empty() {
                                String::new()
                            } else {
                                format!("  // effects: {}", effects.join(", "))
                            };
                            let _akw = if is_async_fn(fn_name) {
                                "async function"
                            } else {
                                "function"
                            };
                            out.push_str(&format!("\n\n{_akw} {fn_name}({ps}) {{{fx}\n"));
                            let bound = crate::codegen::bind_state(body, name);
                            out.push_str(&emit_body(
                                &bound,
                                &aliases,
                                &sigs,
                                Some((name.as_str(), list_fields.as_slice())),
                                &mut 0,
                            ));
                            out.push('}');
                            if fn_name == "main" {
                                has_main = true;
                            }
                        }
                        Item::View {
                            name: view_name,
                            params,
                            body,
                            ..
                        } => {
                            let ps = params
                                .iter()
                                .map(|p| format!("{}: {}", p.name, ty_ts(&p.ty, &aliases)))
                                .collect::<Vec<_>>()
                                .join(", ");
                            let _vkw = if is_async_fn(view_name) {
                                "async function"
                            } else {
                                "function"
                            };
                            let _vret = if is_async_fn(view_name) {
                                "Promise<any>"
                            } else {
                                "any"
                            };
                            out.push_str(&format!("\n\n{_vkw} {view_name}({ps}): {_vret} {{\n"));
                            let bound = crate::codegen::bind_state(body, name);
                            let mut prop_id = 0;
                            out.push_str(&emit_body(
                                &bound,
                                &aliases,
                                &sigs,
                                Some((name.as_str(), list_fields.as_slice())),
                                &mut prop_id,
                            ));
                            out.push('}');
                        }
                        Item::Window {
                            name: win_name,
                            fields,
                        } => {
                            let var_name = format!("_win_{name}_{win_name}");
                            out.push('\n');
                            out.push_str(&emit_window_def_ts(
                                &var_name,
                                win_name,
                                fields,
                                Some(name),
                                &aliases,
                                &sigs,
                            ));
                        }
                        _ => {}
                    }
                }
                let mut agent_props = vec![format!("state: _state_{name}")];
                for f in fns {
                    match f {
                        Item::Fn { name: fn_name, .. } => {
                            agent_props.push(format!("{fn_name}: {fn_name}"));
                        }
                        Item::View {
                            name: view_name, ..
                        } => {
                            agent_props.push(format!("{view_name}: {view_name}"));
                        }
                        Item::Window { name: win_name, .. } => {
                            agent_props.push(format!("{win_name}: _win_{name}_{win_name}"));
                        }
                        _ => {}
                    }
                }
                out.push_str(&format!(
                    "\n\nconst {name} = {{\n  {}\n}};\n",
                    agent_props.join(",\n  ")
                ));
                for f in fns {
                    if let Item::Window { name: win_name, .. } = f {
                        out.push_str(&format!("_win_{name}_{win_name}.agent = {name};\n"));
                        out.push_str(&format!("const {win_name} = _win_{name}_{win_name};\n"));
                    }
                }
            }
            Item::View {
                name, params, body, ..
            } => {
                let ps = params
                    .iter()
                    .map(|p| format!("{}: {}", p.name, ty_ts(&p.ty, &aliases)))
                    .collect::<Vec<_>>()
                    .join(", ");
                out.push_str(&format!("function {name}({ps}): any {{\n"));
                let mut prop_id = 0;
                out.push_str(&emit_body(body, &aliases, &sigs, None, &mut prop_id));
                out.push('}');
            }
            Item::Window { name, fields } => {
                out.push_str(&emit_window_def_ts(
                    name, name, fields, None, &aliases, &sigs,
                ));
            }
            Item::AuthProvider { .. } | Item::Account { .. } => {}
        }
    }
    if has_main {
        out.push_str("\n\nconst _result = await main();\nif (_result !== undefined && _result !== null) console.log(_result);\n");
    }
    if !out.ends_with('\n') {
        out.push('\n');
    }
    out
}

fn emit_body(
    body: &[Stmt],
    aliases: &HashSet<String>,
    sigs: &HashMap<String, Vec<String>>,
    // agent name + its LIST-typed state fields: JS `array += [x]` coerces
    // to a string — list state writes must emit .concat (python parity)
    agent: Option<(&str, &[String])>,
    prop_id: &mut usize,
) -> String {
    if body.is_empty() {
        return String::new();
    }
    let mut out = String::new();
    let last = body.len() - 1;
    for (i, st) in body.iter().enumerate() {
        let line = match &st.kind {
            StmtKind::Let {
                name,
                value,
                stream,
                mutable,
                ..
            } => {
                let kw = if *mutable { "let" } else { "const" };
                if *stream {
                    // the TS runtime now streams (fake parity): swap the
                    // emitted llmCall for llmStream — same opts shape
                    let call = ts(value, aliases, sigs).replacen("rt.llmCall(", "rt.llmStream(", 1);
                    format!("{kw} {name} = {call};")
                } else {
                    format!("{kw} {name} = {};", ts(value, aliases, sigs))
                }
            }
            StmtKind::Assign { name, value } => {
                format!("{name} = {};", ts(value, aliases, sigs))
            }
            // a state write is a checkpoint — the runtime Proxy persists it
            StmtKind::StateWrite { field, op, value } => {
                match agent {
                    Some((target, list_fields)) => {
                        let v = ts(value, aliases, sigs);
                        match op {
                            crate::ast::StateOp::Add if list_fields.iter().any(|f| f == field) => {
                                // Nudge list += is concat; JS += on arrays stringifies
                                format!("_state_{target}.{field} = (_state_{target}.{field}).concat({v});")
                            }
                            crate::ast::StateOp::Set => format!("_state_{target}.{field} = {v};"),
                            crate::ast::StateOp::Add => format!("_state_{target}.{field} += {v};"),
                            crate::ast::StateOp::Sub => format!("_state_{target}.{field} -= {v};"),
                        }
                    }
                    // emit without a prior check pass stays panic-free — the
                    // checker reports E0701; mark the spot instead of panicking
                    None => format!(
                        "// error: state write 'state.{field}' outside an agent block (E0701)"
                    ),
                }
            }
            StmtKind::Assert(e) => format!(
                "if (!({})) throw new Error(\"assertion failed\");",
                ts(e, aliases, sigs)
            ),
            StmtKind::ExprStmt(e) if i == last => format!("return {};", ts(e, aliases, sigs)),
            StmtKind::ExprStmt(e) => format!("{};", ts(e, aliases, sigs)),
            StmtKind::ForAll {
                var,
                gen,
                args,
                body,
            } => emit_for_all(var, gen, args, body, aliases, sigs, agent, prop_id),
            StmtKind::For {
                var,
                idx_var,
                coll,
                body,
            } => {
                let header = match idx_var {
                    Some(idx) => format!(
                        "for (const [{var}, {idx}] of {}.map((_v, _i) => [_v, _i])) {{",
                        ts(coll, aliases, sigs)
                    ),
                    None => format!("for (const {var} of {}) {{", ts(coll, aliases, sigs)),
                };
                let mut s = header;
                for l in emit_body(body, aliases, sigs, agent, prop_id)
                    .trim_end()
                    .lines()
                {
                    s.push_str("\n  ");
                    s.push_str(l);
                }
                s.push_str("\n  }");
                s
            }
            StmtKind::If {
                cond,
                then_body,
                else_body,
            } => {
                let mut s = format!("if ({}) {{", ts(cond, aliases, sigs));
                for l in emit_body(then_body, aliases, sigs, agent, prop_id)
                    .trim_end()
                    .lines()
                {
                    s.push_str("\n  ");
                    s.push_str(l);
                }
                s.push_str("\n  }");
                if let Some(eb) = else_body {
                    s.push_str(" else {");
                    for l in emit_body(eb, aliases, sigs, agent, prop_id)
                        .trim_end()
                        .lines()
                    {
                        s.push_str("\n  ");
                        s.push_str(l);
                    }
                    s.push_str("\n  }");
                }
                s
            }
            StmtKind::IndexAssign {
                collection,
                index,
                value,
            } => {
                format!(
                    "{}[{}] = {};",
                    ts(collection, aliases, sigs),
                    ts(index, aliases, sigs),
                    ts(value, aliases, sigs)
                )
            }
        };
        out.push_str("  ");
        out.push_str(&line);
        out.push('\n');
    }
    out
}

#[allow(clippy::too_many_arguments)]
fn emit_for_all(
    var: &str,
    gen: &str,
    args: &[Expr],
    body: &[Stmt],
    aliases: &HashSet<String>,
    sigs: &HashMap<String, Vec<String>>,
    agent: Option<(&str, &[String])>,
    prop_id: &mut usize,
) -> String {
    *prop_id += 1;
    let arg_list = args
        .iter()
        .map(|a| ts(a, aliases, sigs))
        .collect::<Vec<_>>()
        .join(", ");
    let mut inner = String::new();
    for st in body {
        let line = match &st.kind {
            StmtKind::Let {
                name,
                value,
                mutable,
                ..
            } => {
                let kw = if *mutable { "let" } else { "const" };
                format!("{kw} {name} = {};", ts(value, aliases, sigs))
            }
            StmtKind::Assign { name, value } => {
                format!("{name} = {};", ts(value, aliases, sigs))
            }
            StmtKind::Assert(e) => format!(
                "if (!({})) throw new Error(\"assertion failed\");",
                ts(e, aliases, sigs)
            ),
            StmtKind::ExprStmt(e) => format!("{};", ts(e, aliases, sigs)),
            StmtKind::StateWrite { field, .. } => {
                format!("// error: state write 'state.{field}' outside an agent block (E0701)")
            }
            StmtKind::ForAll {
                var: ivar,
                gen: igen,
                args: iargs,
                body: ibody,
            } => emit_for_all(ivar, igen, iargs, ibody, aliases, sigs, agent, prop_id),
            StmtKind::For {
                var,
                idx_var,
                coll,
                body,
            } => {
                let header = match idx_var {
                    Some(idx) => format!(
                        "for (const [{var}, {idx}] of {}.map((_v, _i) => [_v, _i])) {{",
                        ts(coll, aliases, sigs)
                    ),
                    None => {
                        format!("for (const {var} of {}) {{", ts(coll, aliases, sigs))
                    }
                };
                let mut s = header;
                for l in emit_body(body, aliases, sigs, agent, prop_id)
                    .trim_end()
                    .lines()
                {
                    s.push_str("\n    ");
                    s.push_str(l);
                }
                s.push_str("\n    }");
                s
            }
            StmtKind::If {
                cond,
                then_body,
                else_body,
            } => {
                let mut s = format!("if ({}) {{", ts(cond, aliases, sigs));
                for l in emit_body(then_body, aliases, sigs, agent, prop_id)
                    .trim_end()
                    .lines()
                {
                    s.push_str("\n    ");
                    s.push_str(l);
                }
                s.push_str("\n    }");
                if let Some(eb) = else_body {
                    s.push_str(" else {");
                    for l in emit_body(eb, aliases, sigs, agent, prop_id)
                        .trim_end()
                        .lines()
                    {
                        s.push_str("\n    ");
                        s.push_str(l);
                    }
                    s.push_str("\n    }");
                }
                s
            }
            StmtKind::IndexAssign {
                collection,
                index,
                value,
            } => {
                format!(
                    "{}[{}] = {};",
                    ts(collection, aliases, sigs),
                    ts(index, aliases, sigs),
                    ts(value, aliases, sigs)
                )
            }
        };
        for l in line.lines() {
            inner.push_str("    ");
            inner.push_str(l);
            inner.push('\n');
        }
    }
    format!("rt.forAll(\"{gen}\", [{arg_list}], ({var}) => {{\n{inner}    }}, \"{var}\");")
}

/// Nudge type → simple TS annotation (erasable: identifiers only).
fn ty_ts(t: &TypeExpr, aliases: &HashSet<String>) -> String {
    match t {
        TypeExpr::Named(n) => match n.as_str() {
            "string" => "string".into(),
            "int" | "float" => "number".into(),
            "bool" => "boolean".into(),
            "none" | "()" => "null".into(),
            _ if aliases.contains(n) => "any".into(),
            _ => "any".into(),
        },
        TypeExpr::List(_) => "any[]".into(),
        TypeExpr::Record(_) => "Record<string, any>".into(),
        TypeExpr::Refine(base, ..) => ty_ts(base, aliases),
        TypeExpr::Generic(name, args) => match name.as_str() {
            "Unverified" | "Validated" | "Verified" | "Confidence" if args.len() == 1 => {
                ty_ts(&args[0], aliases)
            }
            _ => format!("/* {name} */ any"),
        },
        TypeExpr::Optional(inner) => format!("{} | null", ty_ts(inner, aliases)),
        TypeExpr::Union(variants) => variants
            .iter()
            .map(|v| ty_ts(v, aliases))
            .collect::<Vec<_>>()
            .join(" | "),
    }
}

fn schema_ts(
    t: &TypeExpr,
    aliases: &HashSet<String>,
    sigs: &HashMap<String, Vec<String>>,
) -> String {
    match t {
        TypeExpr::Named(n) => match n.as_str() {
            "string" => "{\"type\": \"string\"}".into(),
            "int" => "{\"type\": \"integer\"}".into(),
            "float" => "{\"type\": \"number\"}".into(),
            "bool" => "{\"type\": \"boolean\"}".into(),
            "none" | "()" => "{\"type\": \"null\"}".into(),
            _ if aliases.contains(n) => n.clone(),
            _ => "{}".into(),
        },
        TypeExpr::List(inner) => format!(
            "{{\"type\": \"array\", \"items\": {}}}",
            schema_ts(inner, aliases, sigs)
        ),
        TypeExpr::Record(fs) => {
            let props: Vec<String> = fs
                .iter()
                .map(|(k, ft)| format!("\"{k}\": {}", schema_ts(ft, aliases, sigs)))
                .collect();
            let req: Vec<String> = fs.iter().map(|(k, _)| format!("\"{k}\"")).collect();
            format!(
                "{{\"type\": \"object\", \"properties\": {{{}}}, \"required\": [{}]}}",
                props.join(", "),
                req.join(", ")
            )
        }
        TypeExpr::Refine(base, name, args) => {
            let extras: Vec<String> = match (name.as_str(), args.len()) {
                ("range", 2) => vec![
                    format!("\"minimum\": {}", ts(&args[0], aliases, sigs)),
                    format!("\"maximum\": {}", ts(&args[1], aliases, sigs)),
                ],
                ("format", 1) => {
                    let f = match &args[0].kind {
                        ExprKind::Ident(s) | ExprKind::Str(s) => s.as_str(),
                        _ => "url",
                    };
                    vec![format!(
                        "\"format\": \"{}\"",
                        if f == "url" { "uri" } else { f }
                    )]
                }
                _ => vec![],
            };
            match base.as_ref() {
                TypeExpr::Named(n)
                    if matches!(
                        n.as_str(),
                        "string" | "int" | "float" | "bool" | "none" | "()"
                    ) =>
                {
                    let base_pair = match n.as_str() {
                        "string" => "\"type\": \"string\"",
                        "int" => "\"type\": \"integer\"",
                        "float" => "\"type\": \"number\"",
                        "bool" => "\"type\": \"boolean\"",
                        _ => "\"type\": \"string\"",
                    };
                    let all = std::iter::once(base_pair.to_string())
                        .chain(extras)
                        .collect::<Vec<_>>()
                        .join(", ");
                    format!("{{{all}}}")
                }
                _ => {
                    let b = schema_ts(base, aliases, sigs);
                    if extras.is_empty() {
                        b
                    } else {
                        format!("rt.extend({b}, {{{}}})", extras.join(", "))
                    }
                }
            }
        }
        TypeExpr::Generic(name, args) => match name.as_str() {
            "Unverified" | "Validated" | "Verified" | "Confidence" if args.len() == 1 => {
                schema_ts(&args[0], aliases, sigs)
            }
            _ => format!("{{\"type\": \"object\", \"description\": \"{name}\"}}"),
        },
        TypeExpr::Optional(inner) => format!(
            "{{\"anyOf\": [{}, {{\"type\": \"null\"}}]}}",
            schema_ts(inner, aliases, sigs)
        ),
        TypeExpr::Union(variants) => {
            let schemas: Vec<String> = variants
                .iter()
                .map(|v| schema_ts(v, aliases, sigs))
                .collect();
            format!("{{\"anyOf\": [{}]}}", schemas.join(", "))
        }
    }
}

fn expr_schema_ts(
    e: &Expr,
    aliases: &HashSet<String>,
    sigs: &HashMap<String, Vec<String>>,
) -> String {
    match &e.kind {
        ExprKind::Ident(n) => schema_ts(&TypeExpr::Named(n.clone()), aliases, sigs),
        ExprKind::ListLit(xs) if xs.len() == 1 => match &xs[0].kind {
            ExprKind::Ident(n) => schema_ts(
                &TypeExpr::List(Box::new(TypeExpr::Named(n.clone()))),
                aliases,
                sigs,
            ),
            _ => "{}".into(),
        },
        _ => "{}".into(),
    }
}

fn ts(e: &Expr, aliases: &HashSet<String>, sigs: &HashMap<String, Vec<String>>) -> String {
    match &e.kind {
        ExprKind::Int(v) => v.to_string(),
        ExprKind::Float(v) => crate::codegen::fmt_f64(*v),
        ExprKind::Str(s) => js_str(s),
        ExprKind::Money(v, _) => format!("rt.USD(\"{v}\")"),
        ExprKind::Bool(b) => {
            if *b {
                "true".into()
            } else {
                "false".into()
            }
        }
        ExprKind::None => "null".into(),
        ExprKind::Ident(n) => n.clone(),
        ExprKind::ListLit(xs) => {
            format!(
                "[{}]",
                xs.iter()
                    .map(|x| ts(x, aliases, sigs))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        }
        ExprKind::Prompt {
            body,
            interpolations,
        } => {
            if interpolations.is_empty() {
                js_str(body)
            } else {
                let mapping = interpolations
                    .iter()
                    .filter(|k| crate::parser::is_ident_path(k))
                    .map(|k| format!("\"{k}\": {k}"))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("rt.render({}, {{{mapping}}})", js_str(body))
            }
        }
        ExprKind::LlmCall {
            prompt,
            options,
            repair,
        } => llm_ts(prompt, options, *repair, aliases, sigs),
        ExprKind::Call { func, args, kwargs } => {
            let mut parts: Vec<String> = args.iter().map(|a| ts(a, aliases, sigs)).collect();
            // JS has no named arguments — emitting `f(k: v)` was a syntax
            // error. For a known callee, kwargs drop into their declared
            // parameter slots (the checker has already matched the names);
            // for an unknown one, they go as a trailing options object.
            match &func.as_ref().kind {
                ExprKind::Ident(n) if sigs.contains_key(n) => {
                    let order = &sigs[n];
                    for pname in order.iter().skip(args.len()) {
                        match kwargs.iter().find(|(k, _)| k == pname) {
                            Some((_, v)) => parts.push(ts(v, aliases, sigs)),
                            None => parts.push("undefined".into()),
                        }
                    }
                }
                _ => {
                    // single trailing options object — matches Python's
                    // f(1, a=2, b=3); one object per kwarg changed arity
                    if !kwargs.is_empty() {
                        let pairs = kwargs
                            .iter()
                            .map(|(k, v)| format!("{k}: {}", ts(v, aliases, sigs)))
                            .collect::<Vec<_>>()
                            .join(", ");
                        parts.push(format!("{{ {pairs} }}"));
                    }
                }
            }
            match &func.as_ref().kind {
                ExprKind::Ident(n) if n == "len" => {
                    // the checker enforces arity (E0201); stay panic-free if
                    // emit is ever driven without a prior check pass
                    match args.first() {
                        Some(a) => format!("({}.length)", ts(a, aliases, sigs)),
                        None => "(undefined).length".into(),
                    }
                }
                ExprKind::Ident(n) if matches!(n.as_str(), "replay" | "python" | "mcp" | "zip") => {
                    format!("rt.{n}({})", parts.join(", "))
                }
                ExprKind::Field { obj, name } => {
                    if let ExprKind::Ident(prefix) = &obj.kind {
                        if prefix == "browser" {
                            let mut camel_name = String::new();
                            let mut cap = true;
                            for c in name.chars() {
                                if c == '_' {
                                    cap = true;
                                } else if cap {
                                    camel_name.extend(c.to_uppercase());
                                    cap = false;
                                } else {
                                    camel_name.push(c);
                                }
                            }
                            format!("await rt.browser{camel_name}({})", parts.join(", "))
                        } else {
                            format!("{prefix}.{name}({})", parts.join(", "))
                        }
                    } else {
                        format!("{}({})", ts(func, aliases, sigs), parts.join(", "))
                    }
                }
                _ => {
                    let callee_async = match &func.as_ref().kind {
                        ExprKind::Ident(n) => is_async_fn(n),
                        _ => false,
                    };
                    let call = format!("{}({})", ts(func, aliases, sigs), parts.join(", "));
                    if callee_async {
                        format!("await {call}")
                    } else {
                        call
                    }
                }
            }
        }
        ExprKind::Field { obj, name } => format!("{}.{name}", ts(obj, aliases, sigs)),
        ExprKind::Binary { op, l, r } => {
            let o = match op {
                BinOp::And => "&&",
                BinOp::Or => "||",
                other => crate::codegen::op_str(other),
            };
            format!("({} {} {})", ts(l, aliases, sigs), o, ts(r, aliases, sigs))
        }
        ExprKind::Unary { op, x } => match op {
            BinOp::Sub => format!("(-{})", ts(x, aliases, sigs)),
            _ => format!("(!{})", ts(x, aliases, sigs)),
        },
        ExprKind::ParMap {
            coll,
            kwargs,
            params,
            body,
        } => {
            // MVP: sequential map (no worker pool in the TS runtime yet).
            // JS `Array.map` passes (element, index) — a multi-param lambda
            // must take ONE element and destructure the zipped pair
            // ({first, second}), or the second param silently becomes the index.
            let mut s = if params.len() == 2 {
                format!(
                    "rt.parMap({}, (__e) => {{ const {} = __e.first; const {} = __e.second; return {}; }})",
                    ts(coll, aliases, sigs),
                    params[0],
                    params[1],
                    ts(body, aliases, sigs)
                )
            } else {
                format!(
                    "rt.parMap({}, ({}) => {})",
                    ts(coll, aliases, sigs),
                    params.join(", "),
                    ts(body, aliases, sigs)
                )
            };
            if !kwargs.is_empty() {
                s.push_str(
                    "  // warning: par map kwargs ignored by the TS backend (sequential map)",
                );
            }
            s
        }
        // thunks, not values: the runtime wraps each lane's evaluation in
        // its NTF v1.1 branch label — and a plain array return fixes the
        // old un-awaited Promise.all leaking a Promise into `let` bindings
        ExprKind::ParAll(xs) => {
            format!(
                "rt.parAll([{}])",
                xs.iter()
                    .map(|x| format!("() => {}", ts(x, aliases, sigs)))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        }
        ExprKind::ParRace(xs) => {
            format!(
                "rt.parRace([{}])",
                xs.iter()
                    .map(|x| format!("() => {}", ts(x, aliases, sigs)))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        }
        ExprKind::Merge { l, r } => format!(
            "rt.merge({}, {})",
            ts(l, aliases, sigs),
            ts(r, aliases, sigs)
        ),
        ExprKind::Route { arms } => {
            // v1.4: lazy arm values — strings keep model-routing semantics
            let parts = arms
                .iter()
                .map(|(label, value, cond)| match cond {
                    Some(c) => {
                        format!(
                            "[{:?}, () => {}, () => {}]",
                            label,
                            ts(value, aliases, sigs),
                            ts(c, aliases, sigs)
                        )
                    }
                    None => format!("[{:?}, () => {}, null]", label, ts(value, aliases, sigs)),
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!("rt.route({parts})")
        }
        ExprKind::DecideCall {
            questions,
            state,
            options,
        } => {
            let qs = questions
                .iter()
                .map(|(name, q)| match q {
                    DecisionQ::Choice { prompt, options } => format!(
                        "{{ name: {:?}, kind: \"choice\", prompt: {:?}, options: {:?} }}",
                        name, prompt, options
                    ),
                    DecisionQ::Noul { prompt } => {
                        format!(
                            "{{ name: {:?}, kind: \"noul\", prompt: {:?} }}",
                            name, prompt
                        )
                    }
                    DecisionQ::Score { prompt, levels } => format!(
                        "{{ name: {:?}, kind: \"score\", prompt: {:?}, levels: {:?} }}",
                        name, prompt, levels
                    ),
                })
                .collect::<Vec<_>>()
                .join(", ");
            let opts = options
                .iter()
                .map(|(k, v)| format!("{}: {}", js_key(k), ts(v, aliases, sigs)))
                .collect::<Vec<_>>()
                .join(", ");
            format!(
                "rt.decide([{}], {}, {{ {} }})",
                qs,
                ts(state, aliases, sigs),
                opts
            )
        }
        // v1.5 computer-use surface: camelCase rt.* counterparts. The rt.*
        // API takes an options OBJECT (never bare kwargs), at a
        // method-specific position: paste/scroll carry an optional
        // positional before it.
        ExprKind::ComputerCall {
            method,
            args,
            kwargs,
        } => {
            let camel = |m: &str| -> String {
                let mut out = String::with_capacity(m.len());
                let mut up = true; // the leading char capitalizes too
                for c in m.chars() {
                    if c == '_' {
                        up = true;
                    } else if up {
                        out.extend(c.to_uppercase());
                        up = false;
                    } else {
                        out.push(c);
                    }
                }
                out
            };
            let opts = kwargs
                .iter()
                .map(|(k, v)| format!("{}: {}", js_key(k), ts(v, aliases, sigs)))
                .collect::<Vec<_>>()
                .join(", ");
            let call = |positional: Vec<String>| {
                let mut parts = positional;
                if !opts.is_empty() {
                    parts.push(format!("{{ {opts} }}"));
                }
                format!("rt.computer{}({})", camel(method), parts.join(", "))
            };
            match method.as_str() {
                "observe" | "click" | "type" | "key" | "set_value" | "perform" | "drag" => {
                    call(args.iter().map(|a| ts(a, aliases, sigs)).collect())
                }
                "scroll" => {
                    // rt.computerScroll(target, direction, pages = 1, options)
                    let mut positional: Vec<String> =
                        args.iter().map(|a| ts(a, aliases, sigs)).collect();
                    if positional.len() < 3 {
                        positional.push("1".into());
                    }
                    call(positional)
                }
                "paste" => {
                    // rt.computerPaste(text, format = null, options)
                    let mut positional: Vec<String> =
                        args.iter().map(|a| ts(a, aliases, sigs)).collect();
                    if positional.len() < 2 {
                        positional.push("null".into());
                    }
                    call(positional)
                }
                other => format!(
                    "/* warning: unknown computer method {other} (rejected by the checker) */ null"
                ),
            }
        }
        ExprKind::RecordLit(_)
        | ExprKind::Index { .. }
        | ExprKind::If { .. }
        | ExprKind::Spawn(_)
        | ExprKind::Block(_) => "// pack1/pack4 codegen not yet lowered".to_string(),
    }
}

fn js_key(k: &str) -> String {
    let plain = !k.is_empty()
        && k.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')
        && !k.chars().next().unwrap().is_ascii_digit();
    if plain {
        k.to_string()
    } else {
        format!("{k:?}")
    }
}

fn llm_ts(
    prompt: &Expr,
    options: &[(String, Expr)],
    repair: bool,
    aliases: &HashSet<String>,
    sigs: &HashMap<String, Vec<String>>,
) -> String {
    let mut parts = vec![format!("prompt: {}", ts(prompt, aliases, sigs))];
    for (k, v) in options {
        match k.as_str() {
            "schema" => parts.push(format!(
                "schema: rt.schema({})",
                expr_schema_ts(v, aliases, sigs)
            )),
            "model" => parts.push(format!("model: {}", ts(v, aliases, sigs))),
            "budget" => parts.push(format!("budget: {}", ts(v, aliases, sigs))),
            "retry" => parts.push(format!("retry: {}", ts(v, aliases, sigs))),
            "cache" => parts.push(match &v.kind {
                ExprKind::Ident(n) => format!("cache: {}", js_str(n)),
                _ => format!("cache: {}", ts(v, aliases, sigs)),
            }),
            "tags" => parts.push(format!("tags: {}", ts(v, aliases, sigs))),
            "images" => parts.push(format!("images: {}", ts(v, aliases, sigs))),
            other => parts.push(format!(
                "/* warning: unsupported option {other} (ignored) */"
            )),
        }
    }
    if repair {
        parts.push("repair: true".into());
    }
    format!("await rt.llmCall({{{}}})", parts.join(", "))
}

/// `test "run stays within budget"` → `run_stays_within_budget`.
fn slug_ts(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut last_us = true;
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
            last_us = false;
        } else if !last_us {
            out.push('_');
            last_us = true;
        }
    }
    while out.ends_with('_') {
        out.pop();
    }
    if out.is_empty() {
        "unnamed".into()
    } else {
        out
    }
}

/// JS string literal: escape the bare minimum, pass UTF-8 through verbatim.
fn js_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn emit_window_def_ts(
    win_var: &str,
    win_name: &str,
    fields: &[(String, Expr)],
    agent: Option<&str>,
    aliases: &HashSet<String>,
    sigs: &HashMap<String, Vec<String>>,
) -> String {
    let mut title = js_str(win_name);
    let mut width = "undefined".to_string();
    let mut height = "undefined".to_string();
    let mut content = "undefined".to_string();

    for (k, v) in fields {
        match k.as_str() {
            "title" => {
                title = ts(v, aliases, sigs);
            }
            "width" => {
                width = ts(v, aliases, sigs);
            }
            "height" => {
                height = ts(v, aliases, sigs);
            }
            "content" => {
                let bound = if let Some(ag) = agent {
                    crate::codegen::bind_state_expr(v, ag)
                } else {
                    v.clone()
                };
                content = format!("() => {}", ts(&bound, aliases, sigs));
            }
            _ => {}
        }
    }
    format!("const {win_var} = new _Window({title}, {width}, {height}, {content});\n")
}

