//! `nudgec eval` (C1): run a program's function over a JSONL dataset and
//! score it — the "did my change get better or worse?" loop with a CI
//! gate. Rust side orchestrates (check → emit → driver), the Python
//! driver executes each row with whatever provider is configured (fake
//! for $0), and this module turns the per-row results into a report.

use crate::json::{dumps, parse, Json};

pub const EVAL_DRIVER_PY: &str = r#""""Generated by nudgec — eval driver, do not edit."""
import importlib.util, json, sys

spec = importlib.util.spec_from_file_location("nudge_mod", "__MODULE__")
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
rows = [json.loads(l) for l in open("__DATASET__", encoding="utf-8") if l.strip()]
fn_name = "__FN__"
path = "__PATH__"
out_path = "__OUT__"


def _plain(v):
    # dict subclasses (rt.AttrDict) hold their data in the dict itself —
    # check dict before __dict__, or vars() yields an empty shell
    if isinstance(v, dict):
        return {k: _plain(x) for k, x in v.items()}
    if isinstance(v, (list, tuple)):
        return [_plain(x) for x in v]
    if hasattr(v, "__dict__") and not isinstance(v, type):
        return {k: _plain(x) for k, x in vars(v).items()}
    return v


fn = getattr(m, fn_name, None)
if fn is None or not callable(fn):
    print(f"error: no callable function '{fn_name}' in the program", file=sys.stderr)
    sys.exit(1)

results = []
for i, row in enumerate(rows):
    inp = row.get("input")
    args = inp if isinstance(inp, list) else [inp]
    got, ok, err = None, False, None
    try:
        got = _plain(fn(*args))
        exp = row.get("expected")
        cmp = got
        if path:
            for part in path.split("."):
                cmp = cmp[part] if isinstance(cmp, dict) else getattr(cmp, part)
        ok = cmp == exp
    except Exception as e:
        err = f"{type(e).__name__}: {e}"
    rec = {"row": i + 1, "ok": ok, "expected": row.get("expected")}
    if err is not None:
        rec["error"] = err
    else:
        rec["got"] = got
    results.append(rec)

with open(out_path, "w", encoding="utf-8") as f:
    for r in results:
        f.write(json.dumps(r, ensure_ascii=False, default=str) + "\n")
print(f"evaluated {len(results)} row(s)")
"#;

/// Write the driver + module, run it, print the report. `items` must
/// already be checked. Returns the process exit code for the gate.
pub fn run_cli(
    items: &[crate::ast::Item],
    file: &str,
    dataset: &str,
    fname: &str,
    path: &str,
    min_acc: Option<f64>,
) -> i32 {
    use std::fs;
    use std::process::Command;

    let stem = std::path::Path::new(file)
        .file_stem()
        .and_then(|s| s.to_str())
        .unwrap_or("out");
    let out_dir = std::path::Path::new("out");
    if let Err(e) = fs::create_dir_all(out_dir) {
        eprintln!("error: cannot create out/: {e}");
        return 1;
    }
    let module_path = out_dir.join(format!("{stem}.py"));
    if let Err(e) = fs::write(&module_path, crate::codegen::emit(items)) {
        eprintln!("error: cannot write {}: {e}", module_path.display());
        return 1;
    }
    let abs = match module_path.canonicalize() {
        Ok(p) => p,
        Err(e) => {
            eprintln!("error: cannot resolve {}: {e}", module_path.display());
            return 1;
        }
    };
    let results_path = out_dir.join(format!("{stem}_eval_results.jsonl"));
    let driver_src = EVAL_DRIVER_PY
        .replace("__MODULE__", &abs.to_string_lossy())
        .replace("__DATASET__", dataset)
        .replace("__FN__", fname)
        .replace("__PATH__", path)
        .replace("__OUT__", &results_path.to_string_lossy());
    let driver = out_dir.join(format!("{stem}_nudge_eval.py"));
    if let Err(e) = fs::write(&driver, driver_src) {
        eprintln!("error: cannot write {}: {e}", driver.display());
        return 1;
    }
    match Command::new("python3").arg(&driver).status() {
        Ok(st) if st.success() => {}
        Ok(st) => return st.code().unwrap_or(1),
        Err(e) => {
            eprintln!("error: cannot run python3: {e}");
            return 1;
        }
    }
    let results = match fs::read_to_string(&results_path) {
        Ok(s) => s,
        Err(e) => {
            eprintln!("error: cannot read {}: {e}", results_path.display());
            return 1;
        }
    };
    print!("{}", report(&results, min_acc));
    if let Some(min) = min_acc {
        let r = summarize(&results, Some(min));
        let total = r.passed + r.failed;
        if total > 0 {
            let acc = r.passed as f64 / total as f64;
            if acc + 1e-9 < min {
                return 1;
            }
        }
    }
    0
}

pub struct EvalReport {
    pub passed: usize,
    pub failed: usize,
    pub failures: Vec<String>,
}

/// Parse the driver's results JSONL and build the human report.
pub fn summarize(results_src: &str, min_accuracy: Option<f64>) -> EvalReport {
    let mut passed = 0usize;
    let mut failed = 0usize;
    let mut failures = Vec::new();
    for (idx, line) in results_src
        .lines()
        .filter(|l| !l.trim().is_empty())
        .enumerate()
    {
        let Ok(rec) = parse(line) else {
            failed += 1;
            failures.push(format!("  row {}: unparseable result", idx + 1));
            continue;
        };
        let row = rec
            .get("row")
            .and_then(Json::as_num)
            .map(|n| n.to_string())
            .unwrap_or_else(|| (idx + 1).to_string());
        let ok = matches!(rec.get("ok"), Some(Json::Bool(true)));
        if ok {
            passed += 1;
        } else {
            failed += 1;
            let got = rec
                .get("got")
                .map(dumps)
                .or_else(|| rec.get("error").and_then(Json::as_str).map(String::from))
                .unwrap_or_default();
            failures.push(format!(
                "  row {row}: expected {} got {got}",
                rec.get("expected").map(dumps).unwrap_or_default()
            ));
        }
    }
    let total = passed + failed;
    if let Some(min) = min_accuracy {
        if total > 0 {
            let acc = passed as f64 / total as f64;
            if acc + 1e-9 < min {
                failures.push(format!(
                    "  gate: accuracy {:.1}% is below the required {:.1}%",
                    acc * 100.0,
                    min * 100.0
                ));
            }
        }
    }
    EvalReport {
        passed,
        failed,
        failures,
    }
}

pub fn report(results_src: &str, min_accuracy: Option<f64>) -> String {
    let r = summarize(results_src, min_accuracy);
    let total = r.passed + r.failed;
    let mut out = String::new();
    if total == 0 {
        out.push_str("eval: dataset has no rows\n");
        return out;
    }
    let acc = r.passed as f64 / total as f64 * 100.0;
    out.push_str(&format!(
        "eval: {}/{} passed ({acc:.1}% accuracy)\n",
        r.passed, total
    ));
    if !r.failures.is_empty() {
        out.push_str("failures:\n");
        out.push_str(&r.failures.join("\n"));
        out.push('\n');
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn summarize_counts_and_lists_failures() {
        let src = concat!(
            r#"{"row": 1, "ok": true, "expected": "a", "got": "a"}"#,
            "\n",
            r#"{"row": 2, "ok": false, "expected": "b", "got": "x"}"#,
            "\n",
            r#"{"row": 3, "ok": false, "error": "ValueError: bad"}"#,
            "\n",
        );
        let rep = report(src, None);
        assert!(rep.contains("1/3 passed (33.3% accuracy)"), "{rep}");
        assert!(rep.contains(r#"expected "b" got "x""#), "{rep}");
        assert!(rep.contains("ValueError: bad"), "{rep}");
    }

    #[test]
    fn accuracy_gate_fails_below_threshold() {
        let src = r#"{"row": 1, "ok": true, "expected": "a", "got": "a"}"#.to_owned()
            + "\n"
            + r#"{"row": 2, "ok": false, "expected": "b", "got": "x"}"#
            + "\n";
        let rep = report(&src, Some(0.9));
        assert!(
            rep.contains("gate: accuracy 50.0% is below the required 90.0%"),
            "{rep}"
        );
        let rep = report(&src, Some(0.5));
        assert!(!rep.contains("gate:"), "{rep}");
    }

    #[test]
    fn empty_dataset_is_reported_honestly() {
        assert!(report("", None).contains("no rows"));
    }
}
