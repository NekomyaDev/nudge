//! Nudge Python codegen (design §14 contract, v1.10) — day 4–6 scope.
//!
//! Lowers the AST to a single deterministic Python file importing only
//! stdlib + `nudge_runtime`:
//!   type alias  → `Name = rt.schema({...})` JSON-Schema literal (records are
//!                 plain dicts validated at runtime; dataclasses post-MVP)
//!   tool        → `def name(...): return rt.tool_stub("name", [args])` (real
//!                 MCP wiring lands post-MVP; traced as `tool.call` records)
//!   llm call    → `rt.llm_call(prompt=…, schema=rt.schema(…), model=…, …)`
//!   stream let  → `rt.llm_stream(…)` (design §4.5: incremental schema
//!                 validation, early abort on unsatisfiable prefixes)
//!   agent state → `_state_<A> = rt.AgentState("A", {defaults})`; `state.x`
//!                 reads re-root to it, writes checkpoint on every store (§7)
//!   merge       → `rt.merge(l, r)` (design §7: dict union / list dedup)
//!   test block  → `def nudge_test_<slug>():` (design §6.3; run via
//!                 `nudgec test`) with `replay` → `rt.replay`
//!
//! Determinism (design §14 rule d): identical AST ⇒ byte-identical output.

use crate::ast::*;
use std::collections::{HashMap, HashSet};

pub fn emit(items: &[Item]) -> String {
    let aliases: HashSet<String> = items
        .iter()
        .filter_map(|i| match i {
            Item::TypeAlias { name, .. } => Some(name.clone()),
            _ => None,
        })
        .collect();

    let mut out = String::new();
    out.push_str(&format!(
        "\"\"\"Generated by nudgec {} — do not edit.\"\"\"\nimport nudge_runtime as rt\n",
        env!("CARGO_PKG_VERSION")
    ));
    // B6: version compatibility — old runtimes without the hook skip it
    // silently; current runtimes compare against their own __version__
    out.push_str(&format!(
        "if hasattr(rt, \"require_runtime\"):\n    rt.require_runtime(\"{}\")\n",
        env!("CARGO_PKG_VERSION")
    ));
    if has_ui_items(items) {
        out.push_str("\n\n");
        out.push_str(UI_RUNTIME_PY);
    }
    let mut has_main = false;
    // test slugs can collide ("a b" vs "a_b") — suffix duplicates so no
    // test silently overwrites another in the emitted module
    let mut test_slugs: HashMap<String, usize> = HashMap::new();
    for item in items {
        out.push_str("\n\n");
        match item {
            Item::TypeAlias { name, ty } => {
                out.push_str(&format!("{name} = rt.schema({})", schema_py(ty, &aliases)));
            }
            Item::Fn {
                name,
                params,
                effects,
                body,
                ..
            } => {
                if !effects.is_empty() {
                    let set = effects
                        .iter()
                        .map(|e| format!("\"{e}\""))
                        .collect::<Vec<_>>()
                        .join(", ");
                    out.push_str(&format!("@rt.effectful(effects={{{set}}})\n"));
                }
                let ps = params
                    .iter()
                    .map(|p| py_ident(&p.name))
                    .collect::<Vec<_>>()
                    .join(", ");
                let def_name = if name == "main" {
                    "main".to_string()
                } else {
                    py_ident(name)
                };
                out.push_str(&format!("def {def_name}({ps}):\n"));
                out.push_str(&emit_body(body, &aliases, None));
                if name == "main" {
                    has_main = true;
                }
            }
            Item::Tool {
                name,
                params,
                fields,
                ..
            } => {
                let ps = params
                    .iter()
                    .map(|p| p.name.clone())
                    .collect::<Vec<_>>()
                    .join(", ");
                // named arguments (v1.2.1): MCP tools/call expects an
                // `arguments` object keyed by parameter name — FastMCP and
                // most real servers reject the old positional `{"args": []}`
                // framing. The runtime accepts both forms; the stub now
                // always sends the named one.
                let arg_list = params
                    .iter()
                    .map(|p| format!("\"{0}\": {0}", p.name))
                    .collect::<Vec<_>>()
                    .join(", ");
                // design §8: `impl: mcp("server").tool(...)` routes the stub
                // through that server in the runtime registry
                let server = impl_server(fields)
                    .map(|s| format!(", server={}", py_str(&s)))
                    .unwrap_or_default();
                out.push_str(&format!("def {name}({ps}):\n    return rt.tool_stub(\"{name}\", {{{arg_list}}}{server})\n"));
            }
            Item::Test { name, body } => {
                out.push_str(&format!(
                    "def nudge_test_{}():\n",
                    unique_slug(&slug(name), &mut test_slugs)
                ));
                out.push_str(&emit_test_body(body, &aliases));
            }
            Item::Agent { name, state, fns } => {
                // design §7 (v0.2c): state defaults lower to a checkpointed
                // AgentState object; agent fns are plain module-level defs
                let defaults = state
                    .iter()
                    .map(|(f, _, d)| format!("\"{f}\": {}", py(d, &aliases)))
                    .collect::<Vec<_>>()
                    .join(", ");
                out.push_str(&format!(
                    "_state_{name} = rt.AgentState(\"{name}\", {{{defaults}}})\n"
                ));
                for f in fns {
                    match f {
                        Item::Fn {
                            name: fn_name,
                            params,
                            effects,
                            body,
                            ..
                        } => {
                            if !effects.is_empty() {
                                let set = effects
                                    .iter()
                                    .map(|e| format!("\"{e}\""))
                                    .collect::<Vec<_>>()
                                    .join(", ");
                                out.push_str(&format!("@rt.effectful(effects={{{set}}})\n"));
                            }
                            let ps = params
                                .iter()
                                .map(|p| py_ident(&p.name))
                                .collect::<Vec<_>>()
                                .join(", ");
                            let def_fn_name = if fn_name == "main" {
                                "main".to_string()
                            } else {
                                py_ident(fn_name)
                            };
                            out.push_str(&format!("def {def_fn_name}({ps}):\n"));
                            let bound = bind_state(body, name);
                            out.push_str(&emit_body(&bound, &aliases, Some(name)));
                            if fn_name == "main" {
                                has_main = true;
                            }
                        }
                        Item::View {
                            name: view_name,
                            params,
                            body,
                            ..
                        } => {
                            let ps = params
                                .iter()
                                .map(|p| p.name.clone())
                                .collect::<Vec<_>>()
                                .join(", ");
                            out.push_str(&format!("def {view_name}({ps}):\n"));
                            let bound = bind_state(body, name);
                            out.push_str(&emit_body(&bound, &aliases, Some(name)));
                        }
                        Item::Window {
                            name: win_name,
                            fields,
                        } => {
                            let win_var = format!("_win_{name}_{win_name}");
                            out.push_str(&emit_window_def(
                                &win_var,
                                win_name,
                                fields,
                                Some(name),
                                &aliases,
                            ));
                        }
                        _ => {}
                    }
                }
                let mut agent_class = format!("\nclass {name}:\n    state = _state_{name}\n");
                for f in fns {
                    match f {
                        Item::Fn { name: fn_name, .. } => {
                            agent_class
                                .push_str(&format!("    {fn_name} = staticmethod({fn_name})\n"));
                        }
                        Item::View {
                            name: view_name, ..
                        } => {
                            agent_class.push_str(&format!(
                                "    {view_name} = staticmethod({view_name})\n"
                            ));
                        }
                        Item::Window { name: win_name, .. } => {
                            agent_class
                                .push_str(&format!("    {win_name} = _win_{name}_{win_name}\n"));
                        }
                        _ => {}
                    }
                }
                out.push_str(&agent_class);
                for f in fns {
                    if let Item::Window { name: win_name, .. } = f {
                        out.push_str(&format!("_win_{name}_{win_name}.agent = {name}\n"));
                        out.push_str(&format!("{win_name} = _win_{name}_{win_name}\n"));
                    }
                }
            }
            Item::View {
                name, params, body, ..
            } => {
                let ps = params
                    .iter()
                    .map(|p| py_ident(&p.name))
                    .collect::<Vec<_>>()
                    .join(", ");
                let def_name = if name == "main" {
                    "main".to_string()
                } else {
                    py_ident(name)
                };
                out.push_str(&format!("def {def_name}({ps}):\n"));
                out.push_str(&emit_body(body, &aliases, None));
            }
            Item::Window { name, fields } => {
                out.push_str(&emit_window_def(name, name, fields, None, &aliases));
            }
            Item::AuthProvider { .. } | Item::Account { .. } => {}
        }
    }
    if has_main {
        out.push_str("\n\nif __name__ == \"__main__\":\n    _result = main()\n    if _result is not None:\n        print(_result)\n");
    }
    while out.ends_with("\n\n\n") {
        out.pop();
    }
    if !out.ends_with('\n') {
        out.push('\n');
    }
    out
}

fn emit_body(body: &[Stmt], aliases: &HashSet<String>, agent: Option<&str>) -> String {
    if body.is_empty() {
        return "    pass\n".into();
    }
    let mut out = String::new();
    let last = body.len() - 1;
    for (i, st) in body.iter().enumerate() {
        let line = match &st.kind {
            StmtKind::Let {
                name,
                value,
                stream,
                ..
            } => {
                let id = py_ident(name);
                if *stream {
                    match &value.kind {
                        // design §4.5: stream let lowers to the incremental-validating stream call
                        ExprKind::LlmCall {
                            prompt,
                            options,
                            repair,
                        } => {
                            format!("{id} = {}", llm_py(true, prompt, options, *repair, aliases))
                        }
                        _ => format!(
                            "{id} = {}  # warning: stream ignored on non-llm binding",
                            py(value, aliases)
                        ),
                    }
                } else {
                    format!("{id} = {}", py(value, aliases))
                }
            }
            // design §7: a state write is a checkpoint — attribute writes on
            // the AgentState object persist automatically
            StmtKind::StateWrite { field, op, value } => match agent {
                Some(target) => {
                    let op = match op {
                        StateOp::Set => "=",
                        StateOp::Add => "+=",
                        StateOp::Sub => "-=",
                    };
                    format!("_state_{target}.{field} {op} {}", py(value, aliases))
                }
                // emit without a prior check pass stays panic-free — the
                // checker reports E0701; mark the spot instead of panicking
                None => format!(
                    "# error: state write 'state.{field}' outside an agent block (E0701)\n    pass"
                ),
            },
            StmtKind::Assign { name, value } => {
                format!("{} = {}", py_ident(name), py(value, aliases))
            }
            StmtKind::Assert(e) => format!("assert {}", py(e, aliases)),
            // MVP return rule: the fn's final expression is its return value.
            StmtKind::ExprStmt(e) if i == last => format!("return {}", py(e, aliases)),
            StmtKind::ExprStmt(e) => py(e, aliases),
            StmtKind::ForAll { .. } => {
                "# error: for_all outside a test block (E0801)\n    pass".to_string()
            }
            StmtKind::For {
                var,
                idx_var,
                coll,
                body,
            } => {
                let header = match idx_var {
                    Some(idx) => format!("for {idx}, {var} in enumerate({}):", py(coll, aliases)),
                    None => format!("for {var} in {}:", py(coll, aliases)),
                };
                let mut s = header;
                for l in emit_body(body, aliases, agent).trim_end().lines() {
                    s.push_str("\n    ");
                    s.push_str(l);
                }
                s
            }
            StmtKind::If {
                cond,
                then_body,
                else_body,
            } => {
                let mut s = format!("if {}:", py(cond, aliases));
                for l in emit_body(then_body, aliases, agent).trim_end().lines() {
                    s.push_str("\n    ");
                    s.push_str(l);
                }
                if let Some(eb) = else_body {
                    s.push_str("\n    else:");
                    for l in emit_body(eb, aliases, agent).trim_end().lines() {
                        s.push_str("\n    ");
                        s.push_str(l);
                    }
                }
                s
            }
        };
        out.push_str("    ");
        out.push_str(&line);
        out.push('\n');
    }
    out
}

/// Test bodies (design §6.3): no implicit return — asserts do the work.
fn emit_test_body(body: &[Stmt], aliases: &HashSet<String>) -> String {
    emit_stmts(body, aliases, "    ", &mut 0)
}

/// Statement list emitter shared by test blocks and `for_all` property
/// bodies (design §6.4); `indent` grows one level per nested for_all.
fn emit_stmts(
    body: &[Stmt],
    aliases: &HashSet<String>,
    indent: &str,
    prop_id: &mut usize,
) -> String {
    if body.is_empty() {
        return format!("{indent}pass\n");
    }
    let mut out = String::new();
    for st in body {
        let line = match &st.kind {
            StmtKind::Let {
                name,
                value,
                stream,
                ..
            } => {
                if *stream {
                    match &value.kind {
                        // design §4.5: stream let lowers to the incremental-validating stream call
                        ExprKind::LlmCall {
                            prompt,
                            options,
                            repair,
                        } => {
                            format!(
                                "{name} = {}",
                                llm_py(true, prompt, options, *repair, aliases)
                            )
                        }
                        _ => format!(
                            "{name} = {}  # warning: stream ignored on non-llm binding",
                            py(value, aliases)
                        ),
                    }
                } else {
                    format!("{name} = {}", py(value, aliases))
                }
            }
            // the checker reports E0701 — stay panic-free when emit is
            // driven without a prior check pass (fuzz harness does this)
            StmtKind::StateWrite { field, .. } => {
                format!(
                    "# error: state write 'state.{field}' outside an agent block (E0701)\n    pass"
                )
            }
            StmtKind::Assign { name, value } => format!("{name} = {}", py(value, aliases)),
            StmtKind::Assert(e) => format!("assert {}", py(e, aliases)),
            StmtKind::ExprStmt(e) => py(e, aliases),
            StmtKind::ForAll {
                var,
                gen,
                args,
                body,
            } => {
                let id = *prop_id;
                *prop_id += 1;
                let arg_list = args
                    .iter()
                    .map(|a| py(a, aliases))
                    .collect::<Vec<_>>()
                    .join(", ");
                let inner_indent = format!("{indent}    ");
                let inner = emit_stmts(body, aliases, &inner_indent, prop_id);
                format!(
                    "def _prop_{id}({var}):\n{inner}{indent}rt.for_all(\"{gen}\", [{arg_list}], _prop_{id}, \"{var}\")"
                )
            }
            StmtKind::For { .. } => {
                format!("{indent}# pack1 codegen not yet lowered: for loop\n{indent}pass")
            }
            StmtKind::If { .. } => {
                format!("{indent}# pack1 codegen not yet lowered: if statement\n{indent}pass")
            }
        };
        // for_all lines arrive pre-indented (inner body at the nested
        // level, the rt.for_all call at `indent`) — push verbatim
        out.push_str(indent);
        out.push_str(&line);
        out.push('\n');
    }
    out
}

/// Bind `state` reads inside an agent fn to its checkpointed state object
/// (design §7): `state.round` → `_state_<Agent>.round`. State *writes* stay
/// `StmtKind::StateWrite` — emit_body renders them with the same target.
pub fn bind_state(body: &[Stmt], agent: &str) -> Vec<Stmt> {
    body.iter()
        .map(|st| {
            let kind = match &st.kind {
                StmtKind::Let {
                    name,
                    ty,
                    value,
                    stream,
                    mutable,
                } => StmtKind::Let {
                    name: name.clone(),
                    ty: ty.clone(),
                    value: bind_state_expr(value, agent),
                    stream: *stream,
                    mutable: *mutable,
                },
                StmtKind::Assign { name, value } => StmtKind::Assign {
                    name: name.clone(),
                    value: bind_state_expr(value, agent),
                },
                StmtKind::StateWrite { field, op, value } => StmtKind::StateWrite {
                    field: field.clone(),
                    op: *op,
                    value: bind_state_expr(value, agent),
                },
                StmtKind::Assert(e) => StmtKind::Assert(bind_state_expr(e, agent)),
                StmtKind::ExprStmt(e) => StmtKind::ExprStmt(bind_state_expr(e, agent)),
                StmtKind::ForAll {
                    var,
                    gen,
                    args,
                    body,
                } => StmtKind::ForAll {
                    var: var.clone(),
                    gen: gen.clone(),
                    args: args.iter().map(|a| bind_state_expr(a, agent)).collect(),
                    body: bind_state(body, agent),
                },
                StmtKind::For {
                    var,
                    idx_var,
                    coll,
                    body,
                } => StmtKind::For {
                    var: var.clone(),
                    idx_var: idx_var.clone(),
                    coll: bind_state_expr(coll, agent),
                    body: bind_state(body, agent),
                },
                StmtKind::If {
                    cond,
                    then_body,
                    else_body,
                } => StmtKind::If {
                    cond: bind_state_expr(cond, agent),
                    then_body: bind_state(then_body, agent),
                    else_body: else_body.as_ref().map(|b| bind_state(b, agent)),
                },
            };
            Stmt {
                kind,
                span: st.span,
            }
        })
        .collect()
}

pub fn bind_state_expr(e: &Expr, agent: &str) -> Expr {
    let kind = match &e.kind {
        ExprKind::Ident(n) if n == "state" => ExprKind::Ident(format!("_state_{agent}")),
        ExprKind::ListLit(xs) => {
            ExprKind::ListLit(xs.iter().map(|x| bind_state_expr(x, agent)).collect())
        }
        ExprKind::Prompt {
            body,
            interpolations,
        } => {
            // interpolation keys double as Python expressions in the emitted
            // render mapping, so state references must be re-rooted in BOTH
            // the template body and the key list (they must stay in sync)
            let mut body = body.clone();
            let mut interps = Vec::with_capacity(interpolations.len());
            for k in interpolations {
                if k == "state" {
                    body = body.replace("{state}", &format!("{{_state_{agent}}}"));
                    interps.push(format!("_state_{agent}"));
                } else if let Some(rest) = k.strip_prefix("state.") {
                    body = body.replace(
                        &format!("{{state.{rest}}}"),
                        &format!("{{_state_{agent}.{rest}}}"),
                    );
                    interps.push(format!("_state_{agent}.{rest}"));
                } else {
                    interps.push(k.clone());
                }
            }
            ExprKind::Prompt {
                body,
                interpolations: interps,
            }
        }
        ExprKind::LlmCall {
            prompt,
            options,
            repair,
        } => ExprKind::LlmCall {
            prompt: Box::new(bind_state_expr(prompt, agent)),
            options: options
                .iter()
                .map(|(k, v)| (k.clone(), bind_state_expr(v, agent)))
                .collect(),
            repair: *repair,
        },
        ExprKind::Call { func, args, kwargs } => ExprKind::Call {
            func: Box::new(bind_state_expr(func, agent)),
            args: args.iter().map(|a| bind_state_expr(a, agent)).collect(),
            kwargs: kwargs
                .iter()
                .map(|(k, v)| (k.clone(), bind_state_expr(v, agent)))
                .collect(),
        },
        ExprKind::Field { obj, name } => ExprKind::Field {
            obj: Box::new(bind_state_expr(obj, agent)),
            name: name.clone(),
        },
        ExprKind::Binary { op, l, r } => ExprKind::Binary {
            op: op.clone(),
            l: Box::new(bind_state_expr(l, agent)),
            r: Box::new(bind_state_expr(r, agent)),
        },
        ExprKind::Unary { op, x } => ExprKind::Unary {
            op: op.clone(),
            x: Box::new(bind_state_expr(x, agent)),
        },
        ExprKind::ParMap {
            coll,
            kwargs,
            params,
            body,
        } => ExprKind::ParMap {
            coll: Box::new(bind_state_expr(coll, agent)),
            kwargs: kwargs
                .iter()
                .map(|(k, v)| (k.clone(), bind_state_expr(v, agent)))
                .collect(),
            params: params.clone(),
            body: Box::new(bind_state_expr(body, agent)),
        },
        ExprKind::ParAll(xs) => {
            ExprKind::ParAll(xs.iter().map(|x| bind_state_expr(x, agent)).collect())
        }
        ExprKind::ParRace(xs) => {
            ExprKind::ParRace(xs.iter().map(|x| bind_state_expr(x, agent)).collect())
        }
        ExprKind::Merge { l, r } => ExprKind::Merge {
            l: Box::new(bind_state_expr(l, agent)),
            r: Box::new(bind_state_expr(r, agent)),
        },
        ExprKind::Route { arms } => ExprKind::Route {
            arms: arms
                .iter()
                .map(|(label, value, cond)| {
                    (
                        label.clone(),
                        bind_state_expr(value, agent),
                        cond.as_ref().map(|c| bind_state_expr(c, agent)),
                    )
                })
                .collect(),
        },
        ExprKind::DecideCall {
            questions,
            state,
            options,
        } => ExprKind::DecideCall {
            questions: questions.clone(),
            state: Box::new(bind_state_expr(state, agent)),
            options: options
                .iter()
                .map(|(k, v)| (k.clone(), bind_state_expr(v, agent)))
                .collect(),
        },
        leaf => leaf.clone(),
    };
    Expr { kind, span: e.span }
}

/// Find the MCP server in a tool's `impl: mcp("server").tool(...)` field
/// (design §8) — walks the expression for an `mcp("...")` call.
pub fn impl_server(fields: &[(String, Expr)]) -> Option<String> {
    fn find(e: &Expr) -> Option<String> {
        match &e.kind {
            ExprKind::Call { func, args, .. } => {
                if let ExprKind::Ident(n) = &func.as_ref().kind {
                    if n == "mcp" {
                        if let Some(ExprKind::Str(s)) = args.first().map(|a| &a.kind) {
                            return Some(s.clone());
                        }
                    }
                }
                find(func).or_else(|| args.iter().find_map(find))
            }
            ExprKind::Field { obj, .. } => find(obj),
            _ => None,
        }
    }
    fields
        .iter()
        .find(|(k, _)| k == "impl")
        .and_then(|(_, v)| find(v))
}

/// `test "run stays within budget"` → `run_stays_within_budget`.
fn slug(name: &str) -> String {
    let mut out = String::with_capacity(name.len());
    let mut last_us = true; // collapse separators, trim leading
    for ch in name.chars() {
        if ch.is_ascii_alphanumeric() {
            out.push(ch.to_ascii_lowercase());
            last_us = false;
        } else if !last_us {
            out.push('_');
            last_us = true;
        }
    }
    while out.ends_with('_') {
        out.pop();
    }
    if out.is_empty() {
        "unnamed".into()
    } else {
        out
    }
}

/// First use keeps the bare slug; repeats get `_2`, `_3`, … so colliding
/// test names ("a b" / "a_b") both survive in the emitted module.
pub fn unique_slug(base: &str, used: &mut HashMap<String, usize>) -> String {
    let n = used.entry(base.to_string()).or_insert(0);
    *n += 1;
    if *n == 1 {
        base.to_string()
    } else {
        format!("{base}_{n}")
    }
}

fn is_builtin_type(n: &str) -> bool {
    matches!(n, "string" | "int" | "float" | "bool" | "none" | "()")
}

/// TypeExpr → JSON-Schema Python literal (design v1.3 §14).
fn schema_py(t: &TypeExpr, aliases: &HashSet<String>) -> String {
    match t {
        TypeExpr::Named(n) => match n.as_str() {
            "string" => "{\"type\": \"string\"}".into(),
            "int" => "{\"type\": \"integer\"}".into(),
            "float" => "{\"type\": \"number\"}".into(),
            "bool" => "{\"type\": \"boolean\"}".into(),
            "none" | "()" => "{\"type\": \"null\"}".into(),
            _ if aliases.contains(n) => n.clone(),
            _ => "{}".into(), // checker reports the unknown name (E0101)
        },
        TypeExpr::List(inner) => format!(
            "{{\"type\": \"array\", \"items\": {}}}",
            schema_py(inner, aliases)
        ),
        TypeExpr::Record(fs) => {
            // map type (v1.2.1): `{string: T}` (single field keyed by a
            // builtin primitive name) is a string-keyed map, not a record
            // with a field literally named "string" — lower it to
            // additionalProperties so the LLM schema / runtime validation
            // matches the language semantics
            if fs.len() == 1 && is_builtin_type(fs[0].0.as_str()) {
                return format!(
                    "{{\"type\": \"object\", \"additionalProperties\": {}}}",
                    schema_py(&fs[0].1, aliases)
                );
            }
            let props: Vec<String> = fs
                .iter()
                .map(|(k, ft)| format!("\"{k}\": {}", schema_py(ft, aliases)))
                .collect();
            let req: Vec<String> = fs.iter().map(|(k, _)| format!("\"{k}\"")).collect();
            format!(
                "{{\"type\": \"object\", \"properties\": {{{}}}, \"required\": [{}]}}",
                props.join(", "),
                req.join(", ")
            )
        }
        TypeExpr::Refine(base, name, args) => {
            let extras: Vec<String> = match (name.as_str(), args.len()) {
                ("range", 2) => vec![
                    format!("\"minimum\": {}", py(&args[0], aliases)),
                    format!("\"maximum\": {}", py(&args[1], aliases)),
                ],
                ("format", 1) => {
                    let f = match &args[0].kind {
                        ExprKind::Ident(s) | ExprKind::Str(s) => s.as_str(),
                        _ => "url",
                    };
                    vec![format!(
                        "\"format\": \"{}\"",
                        if f == "url" { "uri" } else { f }
                    )]
                }
                _ => vec![],
            };
            match base.as_ref() {
                TypeExpr::Named(n) if is_builtin_type(n) => {
                    let base_pair = match n.as_str() {
                        "string" => "\"type\": \"string\"",
                        "int" => "\"type\": \"integer\"",
                        "float" => "\"type\": \"number\"",
                        "bool" => "\"type\": \"boolean\"",
                        _ => "\"type\": \"string\"",
                    };
                    let all = std::iter::once(base_pair.to_string())
                        .chain(extras)
                        .collect::<Vec<_>>()
                        .join(", ");
                    format!("{{{all}}}")
                }
                _ => {
                    let b = schema_py(base, aliases);
                    if extras.is_empty() {
                        b
                    } else {
                        format!("rt.extend({b}, {{{}}})", extras.join(", "))
                    }
                }
            }
        }
        TypeExpr::Generic(name, args) => match name.as_str() {
            "Unverified" | "Validated" | "Verified" | "Confidence" if args.len() == 1 => {
                schema_py(&args[0], aliases)
            }
            _ => format!("{{\"type\": \"object\", \"description\": \"{name}\"}}"),
        },
        TypeExpr::Optional(inner) => format!(
            "{{\"anyOf\": [{}, {{\"type\": \"null\"}}]}}",
            schema_py(inner, aliases)
        ),
        TypeExpr::Union(variants) => {
            let schemas: Vec<String> = variants.iter().map(|v| schema_py(v, aliases)).collect();
            format!("{{\"anyOf\": [{}]}}", schemas.join(", "))
        }
    }
}

/// A `schema:` option value (Ident / [Ident]) → schema literal.
fn expr_schema_py(e: &Expr, aliases: &HashSet<String>) -> String {
    match &e.kind {
        ExprKind::Ident(n) => schema_py(&TypeExpr::Named(n.clone()), aliases),
        ExprKind::ListLit(xs) if xs.len() == 1 => match &xs[0].kind {
            ExprKind::Ident(n) => schema_py(
                &TypeExpr::List(Box::new(TypeExpr::Named(n.clone()))),
                aliases,
            ),
            _ => "{}".into(),
        },
        _ => "{}".into(),
    }
}

/// Escape Python reserved keywords by suffixing an underscore (e.g. `def` -> `def_`),
/// following standard PEP 8 conventions.
pub fn py_ident(name: &str) -> String {
    const PYTHON_KEYWORDS: &[&str] = &[
        "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class",
        "continue", "def", "del", "elif", "else", "except", "finally", "for", "from", "global",
        "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return",
        "try", "while", "with", "yield",
    ];
    if PYTHON_KEYWORDS.contains(&name) {
        format!("{name}_")
    } else {
        name.to_string()
    }
}

/// f64 → a Python/TS float literal. Rust prints 1.0 as "1" — an INT literal
/// in the emitted code — so a bare integral value gains a trailing ".0".
pub fn fmt_f64(v: f64) -> String {
    let s = v.to_string();
    if s.contains('.') || s.contains('e') || s.contains("inf") || s.contains("NaN") {
        s
    } else {
        format!("{s}.0")
    }
}

fn py(e: &Expr, aliases: &HashSet<String>) -> String {
    match &e.kind {
        ExprKind::Int(v) => v.to_string(),
        ExprKind::Float(v) => fmt_f64(*v),
        ExprKind::Str(s) => py_str(s),
        ExprKind::Money(v, _unit) => format!("rt.USD(\"{v}\")"), // unit pre-checked (E0501)
        ExprKind::Bool(b) => {
            if *b {
                "True".into()
            } else {
                "False".into()
            }
        }
        ExprKind::None => "None".into(),
        ExprKind::Ident(n) => py_ident(n),
        ExprKind::ListLit(xs) => {
            format!(
                "[{}]",
                xs.iter()
                    .map(|x| py(x, aliases))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        }
        ExprKind::Prompt {
            body,
            interpolations,
        } => prompt_py(body, interpolations),
        ExprKind::LlmCall {
            prompt,
            options,
            repair,
        } => llm_py(false, prompt, options, *repair, aliases),
        ExprKind::Call { func, args, kwargs } => {
            let mut parts: Vec<String> = args.iter().map(|a| py(a, aliases)).collect();
            parts.extend(
                kwargs
                    .iter()
                    .map(|(k, v)| format!("{k}={}", py(v, aliases))),
            );
            // runtime-provided builtins get the rt. prefix; len is a real
            // Python builtin and passes through verbatim
            let f = match &func.kind {
                ExprKind::Ident(n) if matches!(n.as_str(), "replay" | "python" | "mcp" | "zip") => {
                    format!("rt.{n}")
                }
                _ => py(func, aliases),
            };
            format!("{}({})", f, parts.join(", "))
        }
        ExprKind::Field { obj, name } => format!("{}.{name}", py(obj, aliases)),
        // always parenthesized: precedence is decided by the Nudge parser,
        // never re-decided by Python
        ExprKind::Binary { op, l, r } => match op {
            BinOp::Add if is_str_expr(l) && !is_str_expr(r) => {
                format!("({} + str({}))", py(l, aliases), py(r, aliases))
            }
            BinOp::Add if is_str_expr(r) && !is_str_expr(l) => {
                format!("(str({}) + {})", py(l, aliases), py(r, aliases))
            }
            _ => format!("({} {} {})", py(l, aliases), op_str(op), py(r, aliases)),
        },
        ExprKind::Unary { op, x } => match op {
            BinOp::Sub => format!("(-{})", py(x, aliases)),
            _ => format!("(not {})", py(x, aliases)),
        },
        ExprKind::ParMap {
            coll,
            kwargs,
            params,
            body,
        } => {
            let mut s = format!(
                "rt.par_map({}, lambda {}: {}",
                py(coll, aliases),
                params.join(", "),
                py(body, aliases)
            );
            for (k, v) in kwargs {
                s.push_str(&format!(", {k}={}", py(v, aliases)));
            }
            s.push(')');
            s
        }
        ExprKind::ParAll(xs) => {
            format!(
                "rt.par_all([{}])",
                xs.iter()
                    .map(|x| py(x, aliases))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        }
        ExprKind::ParRace(xs) => {
            format!(
                "rt.par_race([{}])",
                xs.iter()
                    .map(|x| py(x, aliases))
                    .collect::<Vec<_>>()
                    .join(", ")
            )
        }
        // design §7: reducer join (dict union / list append-dedup at runtime)
        ExprKind::Merge { l, r } => format!("rt.merge({}, {})", py(l, aliases), py(r, aliases)),
        // design §4.4: route block — rt.route picks the first true arm
        ExprKind::Route { arms } => {
            // v1.4: arm values are lazy — a bare string keeps model-routing
            // semantics, other expressions evaluate only when their arm wins
            let parts = arms
                .iter()
                .map(|(label, value, cond)| match cond {
                    Some(c) => format!(
                        "({}, lambda: {}, lambda: {})",
                        py_str(label),
                        py(value, aliases),
                        py(c, aliases)
                    ),
                    None => format!("({}, lambda: {}, None)", py_str(label), py(value, aliases)),
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!("rt.route({parts})")
        }
        ExprKind::DecideCall {
            questions,
            state,
            options,
        } => {
            let py_list = |items: &[String]| -> String {
                format!(
                    "[{}]",
                    items
                        .iter()
                        .map(|o| py_str(o))
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            };
            let qs = questions
                .iter()
                .map(|(name, q)| match q {
                    DecisionQ::Choice { prompt, options } => format!(
                        "{{\"name\": {}, \"kind\": \"choice\", \"prompt\": {}, \"options\": {}}}",
                        py_str(name),
                        py_str(prompt),
                        py_list(options)
                    ),
                    DecisionQ::Noul { prompt } => format!(
                        "{{\"name\": {}, \"kind\": \"noul\", \"prompt\": {}}}",
                        py_str(name),
                        py_str(prompt)
                    ),
                    DecisionQ::Score { prompt, levels } => format!(
                        "{{\"name\": {}, \"kind\": \"score\", \"prompt\": {}, \"levels\": {}}}",
                        py_str(name),
                        py_str(prompt),
                        py_list(levels)
                    ),
                })
                .collect::<Vec<_>>()
                .join(", ");
            let opts = options
                .iter()
                .map(|(k, v)| format!("\"{}\": {}", k, py(v, aliases)))
                .collect::<Vec<_>>()
                .join(", ");
            format!("rt.decide([{qs}], {}, {{{opts}}})", py(state, aliases))
        }
        // v1.5 computer-use surface: every method lowers to its rt.*
        // counterpart with kwargs passed through (allow/deadline/screenshot)
        ExprKind::ComputerCall {
            method,
            args,
            kwargs,
        } => {
            let mut parts: Vec<String> = args.iter().map(|a| py(a, aliases)).collect();
            parts.extend(
                kwargs
                    .iter()
                    .map(|(k, v)| format!("{k}={}", py(v, aliases))),
            );
            format!("rt.computer_{}({})", method, parts.join(", "))
        }
        ExprKind::RecordLit(_)
        | ExprKind::Index { .. }
        | ExprKind::If { .. }
        | ExprKind::Spawn(_)
        | ExprKind::Block(_) => "# pack1/pack4 codegen not yet lowered".to_string(),
    }
}

fn prompt_py(body: &str, interps: &[String]) -> String {
    if interps.is_empty() {
        py_str(body)
    } else {
        // keys are the literal `{...}` contents; values are Python expressions
        // valid in the enclosing scope. Only identifier paths are ever
        // interpolated (parser enforces it) — belt-and-braces re-validation
        // here so a malformed key can never reach a code position.
        let mapping = interps
            .iter()
            .filter(|k| crate::parser::is_ident_path(k))
            .map(|k| format!("\"{k}\": {k}"))
            .collect::<Vec<_>>()
            .join(", ");
        format!("rt.render({}, {{{mapping}}})", py_str(body))
    }
}

fn llm_py(
    stream: bool,
    prompt: &Expr,
    options: &[(String, Expr)],
    repair: bool,
    aliases: &HashSet<String>,
) -> String {
    // NOTE: continuation lines are indented 8 spaces, assuming the call sits
    // directly under a single-depth body line (`return ...` / `x = ...`).
    let mut parts = vec![format!("prompt={}", py(prompt, aliases))];
    for (k, v) in options {
        match k.as_str() {
            "schema" => parts.push(format!("schema=rt.schema({})", expr_schema_py(v, aliases))),
            "model" => parts.push(format!("model={}", py(v, aliases))),
            "budget" => parts.push(format!("budget={}", py(v, aliases))),
            "retry" => parts.push(format!("retry={}", py(v, aliases))),
            "cache" => parts.push(match &v.kind {
                ExprKind::Ident(n) => format!("cache={}", py_str(n)),
                _ => format!("cache={}", py(v, aliases)),
            }),
            "tags" => parts.push(format!("tags={}", py(v, aliases))),
            "images" => parts.push(format!("images={}", py(v, aliases))),
            other => parts.push(format!(
                "# warning: unsupported option {other}={} (ignored)",
                py(v, aliases)
            )),
        }
    }
    if repair {
        parts.push("repair=True".into());
    }
    format!(
        "rt.{}(\n        {},\n    )",
        if stream { "llm_stream" } else { "llm_call" },
        parts.join(",\n        ")
    )
}

pub fn op_str(op: &BinOp) -> &'static str {
    match op {
        BinOp::Add => "+",
        BinOp::Sub => "-",
        BinOp::Mul => "*",
        BinOp::Div => "/",
        BinOp::Mod => "%",
        BinOp::Eq => "==",
        BinOp::NotEq => "!=",
        BinOp::Lt => "<",
        BinOp::LtEq => "<=",
        BinOp::Gt => ">",
        BinOp::GtEq => ">=",
        BinOp::And => "and",
        BinOp::Or => "or",
        BinOp::Not => "not",
    }
}

/// Python string literal: escape the bare minimum, pass UTF-8 through verbatim.
fn py_str(s: &str) -> String {
    let mut out = String::with_capacity(s.len() + 2);
    out.push('"');
    for ch in s.chars() {
        match ch {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn is_str_expr(e: &Expr) -> bool {
    match &e.kind {
        ExprKind::Str(_) => true,
        ExprKind::Binary {
            op: BinOp::Add,
            l,
            r,
        } => is_str_expr(l) || is_str_expr(r),
        _ => false,
    }
}

pub fn has_ui_items(items: &[Item]) -> bool {
    items.iter().any(|i| match i {
        Item::View { .. } | Item::Window { .. } => true,
        Item::Agent { fns, .. } => fns
            .iter()
            .any(|f| matches!(f, Item::Window { .. } | Item::View { .. })),
        _ => false,
    })
}

fn emit_window_def(
    win_var: &str,
    win_name: &str,
    fields: &[(String, Expr)],
    agent: Option<&str>,
    aliases: &HashSet<String>,
) -> String {
    let mut title = py_str(win_name);
    let mut width = "None".to_string();
    let mut height = "None".to_string();
    let mut content = "None".to_string();

    for (k, v) in fields {
        match k.as_str() {
            "title" => {
                title = py(v, aliases);
            }
            "width" => {
                width = py(v, aliases);
            }
            "height" => {
                height = py(v, aliases);
            }
            "content" => {
                let bound = if let Some(ag) = agent {
                    bind_state_expr(v, ag)
                } else {
                    v.clone()
                };
                content = format!("lambda: {}", py(&bound, aliases));
            }
            _ => {}
        }
    }
    format!(
        "{win_var} = _Window(title={title}, width={width}, height={height}, render_fn={content})\n"
    )
}

